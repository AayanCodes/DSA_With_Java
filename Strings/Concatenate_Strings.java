public class Concatenate_Strings {

    public static void main(String[] args) {

        String str1 = "Mohd";
        String str2 = "Aayan";

        String result = str1 + " " + str2;

        System.out.println("Concatenated String = " + result);
    }
}


/*  OUTPUT :

Concatenate String = Mohd Aayan

  */
